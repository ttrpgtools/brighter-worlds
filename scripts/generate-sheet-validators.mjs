import { readFileSync, writeFileSync } from 'node:fs';
import { buildSync } from 'esbuild';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';

const directory = new URL('../src/lib/data/sheet-format/', import.meta.url);
const names = ['sheet-v1.schema.json', 'bundle-v1.schema.json', 'browser-backup-v1.schema.json'];
const schemas = names.map((name) => JSON.parse(readFileSync(new URL(name, directory), 'utf8')));
const ajv = new Ajv2020({ strict: true, allErrors: false, code: { source: true, esm: true } });
ajv.addFormat('uri', /^https?:\/\/[^\s/@?#]+(?:[/?#][^\s]*)?$/);
for (const schema of schemas) ajv.addSchema(schema);
const generated = standalone(ajv, {
  validateSheet: schemas[0].$id,
  validateBundle: schemas[1].$id,
  validateGame: schemas[2].$id,
});
const bundled = buildSync({
  stdin: { contents: generated, resolveDir: fileURLToPath(new URL('..', import.meta.url)) },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  minify: true,
  write: false,
  logLevel: 'error',
}).outputFiles[0].text;
const target = new URL('compiled-validators.js', directory);
const output =
  '// @ts-nocheck\n// Generated by scripts/generate-sheet-validators.mjs. Edit JSON Schemas, then regenerate.\n' +
  bundled;
let current;
try {
  current = readFileSync(target, 'utf8');
} catch {
  /* First generation. */
}
if (current !== output) writeFileSync(target, output);
